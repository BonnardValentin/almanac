use crate::date::Day;
use crate::notes::{self, Note, Stage, Status, INDEX_FILE};
use crate::paths::resolve_dir;
use crate::{has, Res};
use std::path::Path;

// Claude Code loads only this much of MEMORY.md at session start and drops the rest silently.
const MAX_LINES: usize = 200;
const MAX_BYTES: usize = 25_000;
pub const STALE_AFTER_DAYS: i64 = 180;

pub fn is_rule(n: &Note) -> bool {
    n.stage == Stage::Rule && n.status == Status::Active
}

pub fn is_queued(n: &Note) -> bool {
    n.stage == Stage::Investigate && n.status == Status::Active
}

pub fn is_stale(n: &Note, today: Day) -> bool {
    n.stage != Stage::Investigate
        && n.status == Status::Active
        && n.verified_on
            .is_none_or(|d| today.0 - d.0 > STALE_AFTER_DAYS)
}

pub fn render_index(notes: &[Note]) -> String {
    let mut rules: Vec<&Note> = notes.iter().filter(|n| is_rule(n)).collect();
    rules.sort_by(|a, b| (&a.kind, &a.name).cmp(&(&b.kind, &b.name)));
    let mut out = String::from(
        "<!-- Generated by almanac from the notes with stage: rule. Edit the notes, not this file. -->\n",
    );
    let mut kind = "";
    for n in rules {
        if n.kind != kind {
            kind = &n.kind;
            out.push_str(&format!("\n## {kind}\n\n"));
        }
        out.push_str(&format!("- [{}]({}) - {}\n", n.name, n.file, n.description));
    }
    out
}

pub fn write_index(dir: &Path) -> Res {
    let text = render_index(&notes::load_dir(dir)?);
    let lines = text.lines().count();
    if lines > MAX_LINES || text.len() > MAX_BYTES {
        return Err(format!(
            "the Rules view is {lines} lines and {} bytes, over the {MAX_LINES} lines or {MAX_BYTES} bytes \
             Claude Code loads: MEMORY.md was not rewritten. Merge or supersede rules to make room.",
            text.len()
        )
        .into());
    }
    let path = dir.join(INDEX_FILE);
    if std::fs::read_to_string(&path).ok().as_deref() == Some(text.as_str()) {
        return Ok(());
    }
    // Several sessions of one project can rewrite the index at once: each writes its own temp file.
    let tmp = dir.join(format!(".MEMORY.md.{}.tmp", std::process::id()));
    std::fs::write(&tmp, text)?;
    std::fs::rename(tmp, path)?;
    Ok(())
}

pub fn index(args: &[&str]) -> Res {
    write_index(&resolve_dir(args)?)
}

fn print_notes(notes: &[&Note], json: bool) -> Res {
    if !json {
        for n in notes {
            println!("{}", n.path.display());
        }
        return Ok(());
    }
    let rows: Vec<_> = notes
        .iter()
        .map(|n| {
            serde_json::json!({
                "path": n.path,
                "name": n.name,
                "description": n.description,
                "type": n.kind,
                "verified_on": n.verified_on.map(Day::format),
            })
        })
        .collect();
    println!("{}", serde_json::to_string_pretty(&rows)?);
    Ok(())
}

pub fn queue(args: &[&str]) -> Res {
    let notes = notes::load_dir(&resolve_dir(args)?)?;
    let mut queued: Vec<&Note> = notes.iter().filter(|n| is_queued(n)).collect();
    queued.sort_by_key(|n| n.mtime);
    print_notes(&queued, has(args, "--json"))
}

pub fn stale(args: &[&str]) -> Res {
    let today = Day::today();
    let notes = notes::load_dir(&resolve_dir(args)?)?;
    let stale: Vec<&Note> = notes.iter().filter(|n| is_stale(n, today)).collect();
    print_notes(&stale, has(args, "--json"))
}

/// The frontmatter a verdict from the sweep sets. Every verdict records a dated reason.
pub fn verdict_fields(verdict: &str, reason: &str, today: Day) -> Res<Vec<(&'static str, String)>> {
    let checked = (
        "last_check",
        format!("\"{} - {}\"", today.format(), reason.replace('"', "'")),
    );
    let fields = match verdict {
        "verified" => vec![
            ("stage", "verified".into()),
            ("verified_on", today.format()),
            checked,
        ],
        "rule" => vec![
            ("stage", "rule".into()),
            ("verified_on", today.format()),
            checked,
        ],
        "superseded" => vec![("status", "superseded".into()), checked],
        "investigate" => vec![("stage", "investigate".into()), checked],
        other => return Err(format!("unknown verdict `{other}`").into()),
    };
    Ok(fields)
}

/// Applies the sweep workflow's result, `{"verdicts": [{path, verdict, reason}]}`, read on stdin.
/// Only notes inside the memory folder can be touched, whatever the input says.
pub fn apply(args: &[&str]) -> Res {
    let dir = resolve_dir(args)?.canonicalize()?;
    let result: serde_json::Value = serde_json::from_reader(std::io::stdin().lock())?;
    let verdicts = result["verdicts"]
        .as_array()
        .ok_or("expected the sweep's result: {\"verdicts\": [...]}")?;
    let today = Day::today();
    for v in verdicts {
        let field = |k: &str| {
            v[k].as_str()
                .ok_or_else(|| format!("verdict without `{k}`: {v}"))
        };
        let path = Path::new(field("path")?).canonicalize()?;
        if path.parent() != Some(dir.as_path()) || path.file_name().is_some_and(|f| f == INDEX_FILE)
        {
            return Err(format!("{} is not a note in {}", path.display(), dir.display()).into());
        }
        let fields = verdict_fields(field("verdict")?, field("reason")?, today)?;
        let text = std::fs::read_to_string(&path)?;
        std::fs::write(&path, notes::set_fields(&text, &fields))?;
        println!("{} {}", field("verdict")?, path.display());
    }
    write_index(&dir)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::Path;
    use std::time::SystemTime;

    fn note(file: &str, fm: &str) -> Note {
        let text = format!("---\nname: {file}\ndescription: about {file}\n{fm}\n---\n");
        notes::parse(Path::new(file), &text, SystemTime::UNIX_EPOCH)
    }

    #[test]
    fn index_lists_only_active_rules_grouped_by_type() {
        let notes = [
            note("b.md", "type: user\nstage: rule"),
            note("a.md", "type: feedback\nstage: rule"),
            note("c.md", "type: feedback\nstage: verified"),
            note("d.md", "type: feedback\nstage: rule\nstatus: superseded"),
        ];
        let out = render_index(&notes);
        assert!(out.contains("## feedback\n\n- [a.md](a.md) - about a.md\n"));
        assert!(out.contains("## user\n\n- [b.md](b.md) - about b.md\n"));
        assert!(!out.contains("c.md") && !out.contains("d.md"));
    }

    #[test]
    fn staleness() {
        let today = Day::parse("2026-11-10").unwrap();
        assert!(is_stale(
            &note("x.md", "stage: rule\nverified_on: 2026-01-01"),
            today
        ));
        assert!(is_stale(&note("x.md", "stage: verified"), today));
        assert!(!is_stale(
            &note("x.md", "stage: rule\nverified_on: 2026-10-01"),
            today
        ));
        assert!(!is_stale(&note("x.md", "stage: investigate"), today));
    }
}
